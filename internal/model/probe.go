// Package model defines the data types shared by every stage of a parity run:
// the requests that get sent, what was observed, and the conclusions drawn.
package model

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
)

// Safety classifies how intrusive a probe is, so that runs against live
// endpoints can restrict themselves to probes an operator would expect.
type Safety string

const (
	// SafetySafe is a safe HTTP method on a target taken directly from
	// routing configuration or recorded traffic.
	SafetySafe Safety = "safe"
	// SafetyIntrusive is a safe HTTP method on a synthesised target, such as
	// a path with dot segments. A WAF or IDS may flag these.
	SafetyIntrusive Safety = "intrusive"
	// SafetyUnsafe is a non-safe method or a request with a large body.
	SafetyUnsafe Safety = "unsafe"
)

// OriginSource says which generator produced a probe.
type OriginSource string

const (
	// OriginDerived probes come straight from routing rules.
	OriginDerived OriginSource = "derived"
	// OriginMutation probes are variations of a derived probe that target a
	// specific behaviour.
	OriginMutation OriginSource = "mutation"
	// OriginCorpus probes come from recorded traffic.
	OriginCorpus OriginSource = "corpus"
	// OriginControl probes exist to prove that a target routes at all.
	OriginControl OriginSource = "control"
)

// ObjectRef identifies a Kubernetes object without carrying it.
type ObjectRef struct {
	Kind      string `json:"kind"`
	Namespace string `json:"namespace,omitempty"`
	Name      string `json:"name"`
}

// String renders the reference as Kind/namespace/name.
func (r ObjectRef) String() string {
	if r.Namespace == "" {
		return r.Kind + "/" + r.Name
	}
	return r.Kind + "/" + r.Namespace + "/" + r.Name
}

// Origin records why a probe exists. A probe generated by a rule carries that
// rule's ID, so a divergence on it is attributed without guesswork.
type Origin struct {
	Source   OriginSource `json:"source"`
	RuleID   string       `json:"ruleID,omitempty"`
	Object   *ObjectRef   `json:"object,omitempty"`
	Mutation string       `json:"mutation,omitempty"`
}

// Header is a single header field. Order and duplicates are significant, so
// headers are kept as a slice rather than a map.
type Header struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

// BodySpec describes a request body to synthesise.
type BodySpec struct {
	Size        int64  `json:"size"`
	ContentType string `json:"contentType,omitempty"`
}

// Probe is one request to send to every target.
type Probe struct {
	// ID is derived from the request itself, so the same probe has the same
	// ID in every snapshot and observations can be joined across runs.
	ID     string `json:"id"`
	Method string `json:"method"`
	Scheme string `json:"scheme"`
	Host   string `json:"host"`
	// RawTarget is the request-target exactly as it goes on the wire. It is
	// never parsed, cleaned or re-encoded: path normalisation is one of the
	// behaviours under test.
	RawTarget string    `json:"rawTarget"`
	Headers   []Header  `json:"headers,omitempty"`
	Body      *BodySpec `json:"body,omitempty"`
	Origin    Origin    `json:"origin"`
	// Repeat is how many times to send the probe. Values above one are for
	// behaviours that are only visible statistically, such as weighted canaries.
	Repeat int    `json:"repeat"`
	Safety Safety `json:"safety"`
}

// Seal fills defaults, validates the probe and assigns its ID. Generators call
// it on every probe they emit.
func (p *Probe) Seal() error {
	if p.Method == "" {
		p.Method = "GET"
	}
	if p.Scheme == "" {
		p.Scheme = "http"
	}
	if p.Repeat < 1 {
		p.Repeat = 1
	}
	if p.Safety == "" {
		p.Safety = defaultSafety(*p)
	}
	if err := p.Validate(); err != nil {
		return err
	}
	p.ID = "p-" + p.Fingerprint()[:16]
	return nil
}

func defaultSafety(p Probe) Safety {
	switch p.Method {
	case "GET", "HEAD", "OPTIONS":
		if p.Body != nil {
			return SafetyUnsafe
		}
		if p.Origin.Source == OriginMutation {
			return SafetyIntrusive
		}
		return SafetySafe
	default:
		return SafetyUnsafe
	}
}

// Validate rejects probes that could not be written as a single well-formed
// HTTP/1.1 request. The raw prober writes RawTarget and header values to the
// socket verbatim, so anything that could split the request is refused here.
func (p Probe) Validate() error {
	var errs []error
	if p.Scheme != "http" && p.Scheme != "https" {
		errs = append(errs, fmt.Errorf("scheme %q is not http or https", p.Scheme))
	}
	if p.Method == "" || strings.ContainsAny(p.Method, " \t\r\n") {
		errs = append(errs, fmt.Errorf("method %q is not a valid token", p.Method))
	}
	if p.Host == "" {
		errs = append(errs, errors.New("host is empty"))
	} else if strings.ContainsAny(p.Host, " \t\r\n/") {
		errs = append(errs, fmt.Errorf("host %q contains whitespace or a slash", p.Host))
	}
	switch {
	case p.RawTarget == "":
		errs = append(errs, errors.New("request target is empty"))
	case p.RawTarget != "*" && !strings.HasPrefix(p.RawTarget, "/"):
		errs = append(errs, fmt.Errorf("request target %q does not start with a slash", p.RawTarget))
	case strings.ContainsAny(p.RawTarget, " \t\r\n"):
		errs = append(errs, fmt.Errorf("request target %q contains whitespace", p.RawTarget))
	}
	for _, h := range p.Headers {
		if h.Name == "" || strings.ContainsAny(h.Name, " \t\r\n:") {
			errs = append(errs, fmt.Errorf("header name %q is not a valid token", h.Name))
		}
		if strings.ContainsAny(h.Value, "\r\n") {
			errs = append(errs, fmt.Errorf("header %q has a value containing a line break", h.Name))
		}
	}
	if p.Body != nil && p.Body.Size < 0 {
		errs = append(errs, fmt.Errorf("body size %d is negative", p.Body.Size))
	}
	return errors.Join(errs...)
}

// Fingerprint is a stable hash of everything that goes on the wire. Origin,
// Repeat and Safety are deliberately excluded: two generators that arrive at
// the same request produce the same probe.
func (p Probe) Fingerprint() string {
	h := sha256.New()
	field := func(s string) {
		// Length-prefix each field so adjacent fields cannot be confused.
		fmt.Fprintf(h, "%d:%s|", len(s), s)
	}
	field(p.Method)
	field(p.Scheme)
	field(strings.ToLower(p.Host))
	field(p.RawTarget)
	for _, hdr := range p.Headers {
		field(strings.ToLower(hdr.Name))
		field(hdr.Value)
	}
	if p.Body != nil {
		field(fmt.Sprintf("body:%d:%s", p.Body.Size, p.Body.ContentType))
	}
	return hex.EncodeToString(h.Sum(nil))
}
